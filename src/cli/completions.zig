pub fn build(allocator: std.mem.Allocator, shell: Shell) std.mem.Allocator.Error![]u8 {
    return switch (shell) {
        .bash => bash(allocator),
        .zsh => zsh(allocator),
        .fish => fish(allocator),
    };
}

/// Caller owns the result (all three builders).
pub fn bash(allocator: std.mem.Allocator) std.mem.Allocator.Error![]u8 {
    var aw: std.Io.Writer.Allocating = .init(allocator);
    errdefer aw.deinit();
    const w = &aw.writer;
    writeBash(w) catch return error.OutOfMemory;
    return aw.toOwnedSlice();
}

pub fn zsh(allocator: std.mem.Allocator) std.mem.Allocator.Error![]u8 {
    var aw: std.Io.Writer.Allocating = .init(allocator);
    errdefer aw.deinit();
    writeZsh(&aw.writer) catch return error.OutOfMemory;
    return aw.toOwnedSlice();
}

pub fn fish(allocator: std.mem.Allocator) std.mem.Allocator.Error![]u8 {
    var aw: std.Io.Writer.Allocating = .init(allocator);
    errdefer aw.deinit();
    writeFish(&aw.writer) catch return error.OutOfMemory;
    return aw.toOwnedSlice();
}

fn writeBash(w: *std.Io.Writer) std.Io.Writer.Error!void {
    try w.writeAll("# bash completion for ifnh (generated by: ifnh completions bash)\n_ifnh() {\n");
    try w.writeAll("  local cur prev sub i\n  cur=\"${COMP_WORDS[COMP_CWORD]}\"\n  prev=\"${COMP_WORDS[COMP_CWORD-1]}\"\n");
    // The subcommand is the first word that is not a flag or a flag value.
    try w.writeAll("  sub=\"\"\n  for ((i = 1; i < COMP_CWORD; i++)); do\n    case \"${COMP_WORDS[i]}\" in\n      ");
    var first = true;
    for (flags) |f| {
        if (f.value == .none) continue;
        if (!first) try w.writeAll("|");
        first = false;
        try w.writeAll(f.name);
    }
    try w.writeAll(") ((i++)) ;;\n      -*) ;;\n      *) sub=\"${COMP_WORDS[i]}\"; break ;;\n    esac\n  done\n");
    try w.writeAll("  case \"$prev\" in\n    --log-level) mapfile -t COMPREPLY < <(compgen -W \"" ++ log_levels ++ "\" -- \"$cur\"); return ;;\n    --trace) mapfile -t COMPREPLY < <(compgen -f -- \"$cur\"); return ;;\n");
    try w.writeAll("    ");
    first = true;
    for (flags) |f| {
        if (f.value != .text) continue;
        if (!first) try w.writeAll("|");
        first = false;
        try w.writeAll(f.name);
    }
    try w.writeAll(") return ;;\n  esac\n");
    try w.writeAll("  if [[ -z \"$sub\" ]]; then\n    mapfile -t COMPREPLY < <(compgen -W \"");
    for (subcommands) |s| try w.print("{s} ", .{s.name});
    for (flags) |f| try w.print("{s} ", .{f.name});
    try w.writeAll("\" -- \"$cur\")\n    return\n  fi\n  case \"$sub\" in\n");
    for (subcommands) |s| {
        if (s.words.len == 0) continue;
        try w.print("    {s}) mapfile -t COMPREPLY < <(compgen -W \"", .{s.name});
        for (s.words, 0..) |word, i| try w.print("{s}{s}", .{ if (i == 0) "" else " ", word });
        try w.writeAll("\" -- \"$cur\") ;;\n");
    }
    try w.writeAll("  esac\n}\ncomplete -o default -F _ifnh ifnh\n");
}

fn writeZsh(w: *std.Io.Writer) std.Io.Writer.Error!void {
    try w.writeAll("#compdef ifnh\n# zsh completion for ifnh (generated by: ifnh completions zsh)\n_ifnh() {\n  local -a subcommands\n  subcommands=(\n");
    for (subcommands) |s| try w.print("    '{s}:{s}'\n", .{ s.name, s.desc });
    try w.writeAll("  )\n  local state\n  _arguments -C \\\n");
    for (flags) |f| {
        try w.print("    '{s}[{s}]", .{ f.name, f.desc });
        switch (f.value) {
            .none => {},
            .text => try w.writeAll(":value: "),
            .file => try w.writeAll(":file:_files"),
            .log_level => try w.writeAll(":level:(" ++ log_levels ++ ")"),
        }
        try w.writeAll("' \\\n");
    }
    try w.writeAll("    '1: :->sub' \\\n    '*:: :->args'\n  case $state in\n    sub) _describe 'subcommand' subcommands ;;\n    args)\n      case $words[1] in\n");
    for (subcommands) |s| {
        if (s.words.len == 0) continue;
        try w.print("        {s}) compadd --", .{s.name});
        for (s.words) |word| try w.print(" {s}", .{word});
        try w.writeAll(" ;;\n");
    }
    try w.writeAll("      esac ;;\n  esac\n}\nif [ \"$funcstack[1]\" = \"_ifnh\" ]; then\n  _ifnh \"$@\"\nelse\n  compdef _ifnh ifnh\nfi\n");
}

fn writeFish(w: *std.Io.Writer) std.Io.Writer.Error!void {
    try w.writeAll("# fish completion for ifnh (generated by: ifnh completions fish)\ncomplete -c ifnh -f\n");
    for (flags) |f| {
        try w.writeAll("complete -c ifnh ");
        if (std.mem.startsWith(u8, f.name, "--")) {
            try w.print("-l {s}", .{f.name[2..]});
        } else {
            try w.print("-s {s}", .{f.name[1..]});
        }
        switch (f.value) {
            .none => {},
            .text => try w.writeAll(" -r"),
            .file => try w.writeAll(" -rF"),
            .log_level => try w.writeAll(" -x -a '" ++ log_levels ++ "'"),
        }
        try w.print(" -d '{s}'\n", .{f.desc});
    }
    for (subcommands) |s| {
        try w.print("complete -c ifnh -n __fish_use_subcommand -a {s} -d '{s}'\n", .{ s.name, s.desc });
        if (s.words.len == 0) continue;
        try w.print("complete -c ifnh -n '__fish_seen_subcommand_from {s}' -a '", .{s.name});
        for (s.words, 0..) |word, i| try w.print("{s}{s}", .{ if (i == 0) "" else " ", word });
        try w.writeAll("'\n");
    }
}

/// Characters that would need quoting or escaping in at least one shell.
const hazards = "'\"`$:[]\\\n";

test "table text is free of shell-quoting hazards" {
    for (subcommands) |s| {
        try std.testing.expectEqual(@as(?usize, null), std.mem.indexOfAny(u8, s.desc, hazards));
        try std.testing.expectEqual(@as(?usize, null), std.mem.indexOfAny(u8, s.name, hazards ++ " "));
        for (s.words) |word| try std.testing.expectEqual(@as(?usize, null), std.mem.indexOfAny(u8, word, hazards ++ " "));
    }
    for (flags) |f| {
        try std.testing.expectEqual(@as(?usize, null), std.mem.indexOfAny(u8, f.desc, hazards));
        try std.testing.expectEqual(@as(?usize, null), std.mem.indexOfAny(u8, f.name, hazards ++ " "));
    }
}

test "every visible subcommand appears in all three scripts" {
    const a = std.testing.allocator;
    inline for (.{ Shell.bash, Shell.zsh, Shell.fish }) |shell| {
        const text = try build(a, shell);
        defer a.free(text);
        inline for (std.meta.fields(args_mod.Subcommand)) |field| {
            if (comptime std.mem.eql(u8, field.name, "none") or std.mem.eql(u8, field.name, "unknown") or
                std.mem.eql(u8, field.name, "__sandbox-exec")) continue;
            var found = false;
            for (subcommands) |s| found = found or std.mem.eql(u8, s.name, field.name);
            try std.testing.expect(found);
            try std.testing.expect(std.mem.indexOf(u8, text, field.name) != null);
        }
        try std.testing.expect(std.mem.indexOf(u8, text, "__sandbox-exec") == null);
    }
}

test "every table flag is accepted by the real parser" {
    for (flags) |f| {
        const value: []const u8 = if (f.value == .log_level) "info" else "1";
        const argv: []const []const u8 = if (f.value == .none) &.{ f.name, "help" } else &.{ f.name, value, "help" };
        const p = try args_mod.parse(argv);
        try std.testing.expectEqual(args_mod.Subcommand.help, p.subcommand);
    }
}

test "scripts avoid command substitution and backticks" {
    const a = std.testing.allocator;
    inline for (.{ Shell.bash, Shell.zsh, Shell.fish }) |shell| {
        const text = try build(a, shell);
        defer a.free(text);
        try std.testing.expect(std.mem.indexOf(u8, text, "$(") == null);
        try std.testing.expect(std.mem.indexOfScalar(u8, text, '`') == null);
    }
}

test "bash script passes bash -n" {
    const a = std.testing.allocator;
    const text = try bash(a);
    defer a.free(text);
    var tmp = std.testing.tmpDir(.{});
    defer tmp.cleanup();
    try tmp.dir.writeFile(std.testing.io, .{ .sub_path = "ifnh.bash", .data = text });
    var dir_buf: [std.fs.max_path_bytes]u8 = undefined;
    const dir_path = dir_buf[0..try tmp.dir.realPath(std.testing.io, &dir_buf)];
    const path = try std.fmt.allocPrint(a, "{s}/ifnh.bash", .{dir_path});
    defer a.free(path);
    const result = std.process.run(a, std.testing.io, .{ .argv = &.{ "bash", "-n", path } }) catch |err| switch (err) {
        error.FileNotFound => return error.SkipZigTest, // no bash on this host
        else => return err,
    };
    defer a.free(result.stdout);
    defer a.free(result.stderr);
    try std.testing.expectEqual(std.process.Child.Term{ .exited = 0 }, result.term);
}
