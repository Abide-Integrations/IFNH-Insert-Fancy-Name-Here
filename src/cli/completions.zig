//! Shell completion scripts (F-02): `ifnh completions <bash|zsh|fish>`.
//!
//! One shared table of subcommands and global flags feeds all three
//! builders, so the scripts cannot drift from each other. Builders are pure:
//! they return the script text and never touch the filesystem or process.
//! Descriptions are plain text; the table test rejects any character that
//! would need quoting in one of the shells, so no escaping is done below.

const std = @import("std");
const args_mod = @import("args.zig");

const Shell = args_mod.Shell;

const Entry = struct {
    name: []const u8,
    desc: []const u8,
    /// Words completed after the subcommand (second-level commands).
    words: []const []const u8 = &.{},
};

