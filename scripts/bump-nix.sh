#!/bin/sh
# Write nix/artifacts.nix (version + the four sha256 values) for a release
# (ACTIVE_PLAN F-08); flake.nix reads it.
#   scripts/bump-nix.sh [<version>] [--dist-dir <dir>] [--out <file>]
#   scripts/bump-nix.sh --placeholder [--out <file>]
# <version> defaults to scripts/check-version.sh --print. Hashes come from the
# published .sha256 files (scripts/release-sha256.sh; --dist-dir or
# IFNH_RELEASE_BASE_URL as there). --placeholder writes all-zero hashes, marked
# PLACEHOLDER, so `nix flake show` evaluates before a release exists; `nix build`
# then fails with a hash mismatch until this is run against a real release.
# --out defaults to nix/artifacts.nix in the repo.
set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
ver=""
dist=""
out="$root/nix/artifacts.nix"
placeholder=0
while [ $# -gt 0 ]; do
  case "$1" in
    --dist-dir) [ $# -ge 2 ] || { echo "bump-nix: --dist-dir needs a value" >&2; exit 2; }; dist="$2"; shift ;;
    --out) [ $# -ge 2 ] || { echo "bump-nix: --out needs a value" >&2; exit 2; }; out="$2"; shift ;;
    --placeholder) placeholder=1 ;;
    -*) echo "bump-nix: unknown argument '$1'" >&2; exit 2 ;;
    *) ver="${1#v}" ;;
  esac
  shift
done
[ -n "$ver" ] || ver=$("$root/scripts/check-version.sh" --print)
sha() {
  if [ "$placeholder" = 1 ]; then printf '%064d\n' 0; else "$root/scripts/release-sha256.sh" "$ver" "$1" ${dist:+"$dist"}; fi
}

# Assigned first so a missing/bad .sha256 aborts before anything is written.
lx64=$(sha linux-x86_64-musl)
larm=$(sha linux-aarch64-musl)
dx64=$(sha macos-x86_64)
darm=$(sha macos-aarch64)
note="# Generated by scripts/bump-nix.sh; do not edit by hand."
if [ "$placeholder" = 1 ]; then
  note="# PLACEHOLDER hashes (all zero): run scripts/bump-nix.sh against a real release before 'nix build'."
fi
mkdir -p "$(dirname "$out")"
cat > "$out" << EOF
$note
{
  version = "$ver";
  platforms = {
    x86_64-linux = { suffix = "linux-x86_64-musl"; sha256 = "$lx64"; };
    aarch64-linux = { suffix = "linux-aarch64-musl"; sha256 = "$larm"; };
    x86_64-darwin = { suffix = "macos-x86_64"; sha256 = "$dx64"; };
    aarch64-darwin = { suffix = "macos-aarch64"; sha256 = "$darm"; };
  };
}
EOF
echo "bump-nix: wrote $out for $ver" >&2
